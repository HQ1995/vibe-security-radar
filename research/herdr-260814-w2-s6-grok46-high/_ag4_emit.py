def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def run(cmd, cwd=None, timeout=30):
    try:
        p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout)
        return p.returncode, (p.stdout or "").strip(), (p.stderr or "").strip()
    except Exception as e:
        return 99, "", str(e)


def find_clone(repo: str) -> str | None:
    owner, name = repo.split("/", 1)
    needle = f"{owner}__{name}"
    hits = []
    for dirpath, dirnames, filenames in os.walk(CLONE_ROOT):
        if dirpath.rstrip("/").endswith(needle) and (Path(dirpath) / ".git").exists():
            hits.append(dirpath)
            dirnames[:] = []
    if not hits:
        return None
    hits.sort(key=lambda p: (0 if "commit-gn" in p else 1, p))
    return hits[0]


