def inspect_sha(clone: str | None, sha: str) -> dict:
    rec = {"sha": sha, "exists": False, "ai": False, "author": None, "subject": None, "body": None, "parents": [], "files": []}
    if not clone:
        return rec
    code, out, _ = run(["git", "cat-file", "-t", sha], cwd=clone)
    if code != 0 or out.strip() != "commit":
        return rec
    rec["exists"] = True
    _, body, _ = run(["git", "show", "-s", "--format=%an <%ae>%n%cn <%ce>%n%P%n%s%n%b", sha], cwd=clone)
    lines = body.splitlines()
    rec["author"] = lines[0] if lines else None
    rec["parents"] = (lines[2].split() if len(lines) > 2 else [])
    rec["subject"] = lines[3] if len(lines) > 3 else None
    rec["body"] = "\n".join(lines[4:]) if len(lines) > 4 else ""
    blob = "\n".join(lines)
    rec["ai"] = bool(AI_RE.search(blob))
    _, files, _ = run(["git", "diff-tree", "--no-commit-id", "--name-only", "-r", sha], cwd=clone)
    rec["files"] = [f for f in files.splitlines() if f][:40]
    return rec


def try_fetch(clone: str, sha: str, repo: str) -> dict:
    rec = inspect_sha(clone, sha)
