"""Phase 2: enumerate the pagination-complete advisory delta (frozen -> current)
across advisories/unreviewed and advisories/github-reviewed, apply baseline
exclusions and identity-collision routing.

Emits:
  delta-manifest.jsonl   - all changed paths (routing notes)
  reviewed-delta.jsonl   - github-reviewed rows only (731 A / 148 M / 0 D expected)
  delta-summary.json
"""
